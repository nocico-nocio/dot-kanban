export const locales = ["en", "ja", "ko", "zh-TW", "zh-CN"] as const;
export type Locale = (typeof locales)[number];
const index: Record<Locale, number> = {
  en: 0,
  ja: 1,
  ko: 2,
  "zh-TW": 3,
  "zh-CN": 4,
};
export function detectLocale(value: string): Locale {
  const tag = value.toLowerCase();
  if (tag.startsWith("ja")) return "ja";
  if (tag.startsWith("ko")) return "ko";
  if (tag.startsWith("zh"))
    return /hant|tw|hk|mo/.test(tag) ? "zh-TW" : /hans|cn|sg/.test(tag) ? "zh-CN" : "zh-CN";
  return "en";
}
export function initialLocale(storage: Pick<Storage, "getItem">, browserLanguage: string): Locale {
  const saved = storage.getItem("dot-kanban-locale");
  return saved && locales.includes(saved as Locale)
    ? (saved as Locale)
    : detectLocale(browserLanguage);
}
