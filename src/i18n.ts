export type MessageKey = keyof typeof messages;
export const t = (locale: Locale, key: MessageKey) => messages[key][index[locale]];
export const formatDate = (locale: Locale, value: string) =>
  new Intl.DateTimeFormat(locale, {
    dateStyle: "medium",
    timeStyle: "short",
  }).format(new Date(value));
export const formatDue = (locale: Locale, value: string) =>
  new Intl.DateTimeFormat(locale, {
    dateStyle: "medium",
    timeZone: "UTC",
  }).format(new Date(`${value}T00:00:00Z`));
export const formatNumber = (locale: Locale, value: number) =>
  new Intl.NumberFormat(locale).format(value);
export function formatElapsed(locale: Locale, value: string, now: number): string {
  const minutes = Math.max(0, Math.floor((now - Date.parse(value)) / 60_000));
  if (minutes < 1) return t(locale, "justNow");
  if (minutes < 60) return `${minutes}m`;
  if (minutes < 1440) return `${Math.floor(minutes / 60)}h`;
  return `${Math.floor(minutes / 1440)}d`;
}
